import { test, expect, fillRegistration, submitLogin, signOut, setupTeam, create, mailLink } from '../support/e2e'

const email = 'new-user@registration.example.test'
const secret = 'Registration-password-2026!'

test('a new user registers, confirms the address, signs in, creates a team and cannot overwrite an existing account', async ({ page }, info) => {
  await page.goto('/login')
  await page.getByRole('link', { name: 'Utwórz konto', exact: true }).click()
  await fillRegistration(page, email, secret)
  await page.getByRole('button', { name: 'Pokaż hasło' }).click()
  await expect(page.getByLabel('Hasło', { exact: true })).toHaveAttribute('type', 'text')
  await page.getByRole('button', { name: 'Ukryj hasło' }).click()
  await page.screenshot({ path: info.outputPath('registration.png'), fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Utwórz konto', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Rejestracja przyjęta')
  await expect(page.getByLabel('Adres e-mail')).toHaveValue(email)
  await expect(page.getByLabel('Hasło', { exact: true })).toHaveValue('')
  expect((await page.request.get('/api/me')).status()).toBe(401)
  await submitLogin(page, email, secret)
  await expect(page.getByRole('alert')).toContainText('Potwierdź adres e-mail')
  await page.goto(await mailLink(page.request, email, 'verify-email'))
  await expect(page.getByText('Adres e-mail został potwierdzony.')).toBeVisible()
  await page.goto('/login')
  await submitLogin(page, email, secret)
  await expect(page).toHaveURL(/\/dashboard$/)
  await expect(page.getByRole('heading', { name: 'Cześć, Registration.' })).toBeVisible()
  expect(await (await page.request.get('/api/teams')).json()).toEqual([])
  await page.getByRole('link', { name: 'Przejdź do zespołów', exact: true }).click()
  await page.getByRole('button', { name: 'Utwórz zespół', exact: true }).click()
  const modal = page.getByRole('dialog', { name: 'Utwórz zespół' })
  await modal.getByLabel('Nazwa zespołu').fill('New registered team')
  await modal.getByRole('button', { name: 'Utwórz zespół', exact: true }).click()
  await expect(modal).not.toBeVisible()
  await expect(page.getByRole('region', { name: 'Wybrany zespół' })).toContainText('Właściciel')
  await signOut(page)
  await page.goto('/register')
  await fillRegistration(page, email.toUpperCase(), 'Different-password-2026!')
  await page.getByRole('button', { name: 'Utwórz konto', exact: true }).click()
  // The same answer as for a new address, so sign-up reveals nothing; the original password is untouched.
  await expect(page.getByRole('status')).toContainText('Rejestracja przyjęta')
  await submitLogin(page, email, secret)
  await expect(page).toHaveURL(/\/dashboard/)
})

test('registration preserves an invitation and a new member can record work after joining', async ({ page, browser }, info) => {
  const { team, project } = await setupTeam(page, `Registration ${info.project.name}`)
  const invitation = await create(page.request, `/api/teams/${team.id}/invites`, { expiresAt: new Date(Date.now() + 3600000).toISOString(), maxUses: 1 })
  const newContext = await browser.newContext({ baseURL: new URL(page.url()).origin })
  try {
    const newcomer = await newContext.newPage()
    await newcomer.goto(`/invite/${invitation.token}`)
    await expect(newcomer).toHaveURL(/\/login\?returnTo=/)
    await newcomer.getByRole('link', { name: 'Utwórz konto', exact: true }).click()
    await expect(newcomer).toHaveURL(/\/register\?returnTo=/)
    await fillRegistration(newcomer, email, secret, 'Invited User')
    await newcomer.getByRole('button', { name: 'Utwórz konto', exact: true }).click()
    await expect(newcomer.getByRole('heading', { name: 'Zaloguj się' })).toBeVisible()
    expect(new URL(newcomer.url()).searchParams.get('returnTo')).toBe(`/invite/${invitation.token}`)
    const loginWithInvitation = newcomer.url()
    await newcomer.goto(await mailLink(newcomer.request, email, 'verify-email'))
    await expect(newcomer.getByText('Adres e-mail został potwierdzony.')).toBeVisible()
    await newcomer.goto(loginWithInvitation)
    await submitLogin(newcomer, email, secret)
    await expect(newcomer.getByRole('heading', { name: 'Zaproszenie do zespołu' })).toBeVisible()
    expect(await (await newcomer.request.get('/api/teams')).json()).toEqual([])
    await newcomer.getByRole('button', { name: 'Dołącz do zespołu' }).click()
    await newcomer.getByRole('link', { name: 'Przejdź do zespołu', exact: true }).click()
    await expect(newcomer.getByRole('region', { name: 'Wybrany zespół' })).toContainText('Członek')
    await expect(newcomer.getByRole('button', { name: 'Zaproś do zespołu' })).toHaveCount(0)
    await newcomer.goto(`/time?team=${team.id}`)
    await newcomer.getByLabel('Projekt', { exact: true }).selectOption(project.id)
    await newcomer.getByRole('button', { name: 'Dodaj wpis ręczny' }).click()
    const modal = newcomer.getByRole('dialog')
    await modal.getByLabel('Minuty').fill('15')
    await modal.getByLabel('Opis pracy', { exact: false }).fill('New member work')
    await modal.getByRole('button', { name: 'Zapisz wpis' }).click()
    await expect(modal).not.toBeVisible()
    await expect(newcomer.getByRole('region', { name: 'Wpisy historii czasu' })).toContainText('New member work')
    const summary = await (await page.request.get(`/api/teams/${team.id}/reports/summary`)).json()
    expect(summary.totals.durationSeconds).toBe(900)
  } finally {
    await newContext.close()
  }
})
