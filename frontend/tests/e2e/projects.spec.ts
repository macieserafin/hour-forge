import { test, expect, owner as ownerEmail, member as memberEmail, password as ownerPassword, memberPassword, login as signIn, write } from '../support/e2e'

test('select team, create, inspect, edit and archive projects', { tag: '@responsive' }, async ({ page }, testInfo) => {
  await signIn(page, ownerEmail!, ownerPassword!)
  const suffix = `${testInfo.project.name} ${Date.now()}`
  const first = await write(page.request, '/api/teams', { name: `Studio ${suffix}`, timezone: 'UTC' })
  const second = await write(page.request, '/api/teams', { name: `Other ${suffix}`, timezone: 'UTC' })
  await page.goto(`/teams?team=${first.id}`)
  await page.getByRole('link', { name: 'Projekty zespołu', exact: true }).click()
  await expect(page.getByLabel('Zespół', { exact: true })).toHaveValue(first.id)
  await expect(page.getByText('Brak aktywnych projektów.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Utwórz projekt', exact: true }).click()
  const form = page.getByRole('dialog', { name: 'Utwórz projekt', exact: true })
  await expect(form).toContainText(first.name)
  await form.getByLabel('Nazwa projektu').fill('   ')
  await form.getByRole('button', { name: 'Utwórz projekt', exact: true }).click()
  await expect(form.getByRole('alert')).toHaveText('Wpisz nazwę projektu.')
  const projectName = `Projekt ${suffix}`
  await form.getByLabel('Nazwa projektu').fill(`  ${projectName}  `)
  await form.getByLabel('Opis', { exact: false }).fill('Pierwszy opis\nDruga linia')
  await page.screenshot({ path: testInfo.outputPath('project-create-modal.png'), fullPage: false, animations: 'disabled' })
  // The textarea participates in the modal's keyboard focus loop, followed by the colour choice (one tab stop), the repository field and the buttons.
  await form.getByLabel('Opis', { exact: false }).focus()
  await page.keyboard.press('Tab')
  await expect(form.getByLabel('Bez koloru')).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(form.getByLabel('Repozytorium GitHub', { exact: false })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(form.getByRole('button', { name: 'Anuluj' })).toBeFocused()
  await form.getByRole('button', { name: 'Utwórz projekt', exact: true }).click()
  await expect(form).not.toBeVisible()
  const row = page.getByRole('row').filter({ has: page.getByRole('button', { name: projectName, exact: true }) })
  await expect(row).toContainText('Aktywny')
  await page.reload()
  await expect(page.getByLabel('Zespół', { exact: true })).toHaveValue(first.id)
  await row.getByRole('button', { name: projectName, exact: true }).click()
  const details = page.getByRole('dialog', { name: 'Szczegóły projektu' })
  await expect(details).toContainText('Pierwszy opis')
  await expect(details).toContainText(first.name)
  await details.getByRole('button', { name: 'Edytuj projekt', exact: true }).click()
  const edit = page.getByRole('dialog', { name: 'Edytuj projekt', exact: true })
  await expect(edit.getByLabel('Nazwa projektu')).toHaveValue(projectName)
  const changed = `${projectName} — zmiana`
  await edit.getByLabel('Nazwa projektu').fill(changed)
  await edit.getByLabel('Opis', { exact: false }).fill('')
  await edit.getByRole('button', { name: 'Zapisz zmiany' }).click()
  await expect(edit).not.toBeVisible()
  await page.getByRole('button', { name: `Archiwizuj projekt ${changed}`, exact: true }).click()
  const archive = page.getByRole('dialog', { name: 'Archiwizuj projekt', exact: true })
  await archive.getByRole('button', { name: 'Anuluj' }).click()
  await expect(page.getByRole('button', { name: changed, exact: true })).toBeVisible()
  await page.getByRole('button', { name: `Archiwizuj projekt ${changed}`, exact: true }).click()
  await page.getByRole('dialog', { name: 'Archiwizuj projekt', exact: true }).getByRole('button', { name: 'Archiwizuj projekt', exact: true }).click()
  await expect(page.getByRole('button', { name: changed, exact: true })).toHaveCount(0)
  await page.getByLabel('Status projektów').selectOption('all')
  const archivedRow = page.getByRole('row').filter({ has: page.getByRole('button', { name: changed, exact: true }) })
  await expect(archivedRow).toContainText('Archiwalny')
  await expect(archivedRow.getByRole('button', { name: /Edytuj|Archiwizuj/ })).toHaveCount(0)
  await page.getByRole('button', { name: changed, exact: true }).click()
  await expect(details).toContainText('Brak opisu projektu.')
  await expect(details.getByRole('button', { name: 'Edytuj projekt' })).toHaveCount(0)
  await details.getByRole('button', { name: 'Zamknij', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('projects-archive.png'), fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByLabel('Zespół', { exact: true }).selectOption(second.id)
  await expect(page).toHaveURL(new RegExp(`team=${second.id}`))
  await expect(page.getByLabel('Status projektów')).toHaveValue('active')
  await expect(page.getByText('Brak aktywnych projektów.', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: changed, exact: true })).toHaveCount(0)
  const firstProjects = await page.request.get(`/api/teams/${first.id}/projects?includeArchived=true`)
  const stored = await firstProjects.json()
  expect(stored).toHaveLength(1)
  expect(stored[0]).toMatchObject({ teamId: first.id, name: changed, description: null })
  expect(stored[0].archivedAt).toBeTruthy()
  const secondProjects = await page.request.get(`/api/teams/${second.id}/projects?includeArchived=true`)
  expect(await secondProjects.json()).toEqual([])
})

test('member sees projects without management actions and inaccessible team is not replaced', async ({ page, browser }, testInfo) => {
  await signIn(page, ownerEmail!, ownerPassword!)
  const team = await write(page.request, '/api/teams', { name: `Member view ${testInfo.project.name} ${Date.now()}`, timezone: 'UTC' })
  const project = await write(page.request, `/api/teams/${team.id}/projects`, { name: 'Shared project', description: 'Team description' })
  const invite = await write(page.request, `/api/teams/${team.id}/invites`, { expiresAt: new Date(Date.now() + 3600000).toISOString(), maxUses: 1 })
  const context = await browser.newContext({ baseURL: testInfo.project.use.baseURL, viewport: testInfo.project.use.viewport })
  try {
    const memberPage = await context.newPage()
    await signIn(memberPage, memberEmail!, memberPassword!)
    await write(memberPage.request, `/api/invites/${invite.token}/accept`, {})
    await memberPage.goto(`/projects?team=${team.id}`)
    await expect(memberPage.getByRole('button', { name: 'Shared project', exact: true })).toBeVisible()
    await expect(memberPage.getByRole('button', { name: /Utwórz projekt|Edytuj projekt|Archiwizuj projekt/ })).toHaveCount(0)
    await memberPage.getByRole('button', { name: 'Shared project', exact: true }).click()
    await expect(memberPage.getByRole('dialog')).toContainText('Team description')
    await expect(memberPage.getByRole('button', { name: 'Edytuj projekt' })).toHaveCount(0)
    await memberPage.getByRole('button', { name: 'Zamknij', exact: true }).click()
    await memberPage.screenshot({ path: testInfo.outputPath('projects-member.png'), fullPage: true, animations: 'disabled' })
    const inaccessible = '00000000-0000-0000-0000-000000000000'
    await memberPage.goto(`/projects?team=${inaccessible}`)
    await expect(memberPage.getByRole('alert')).toContainText('Ten zespół nie istnieje lub nie masz do niego dostępu.')
    await expect(memberPage).toHaveURL(new RegExp(`team=${inaccessible}`))
    await expect(memberPage.getByRole('button', { name: project.name, exact: true })).toHaveCount(0)
    await memberPage.getByLabel('Zespół', { exact: true }).selectOption(team.id)
    await expect(memberPage.getByRole('button', { name: project.name, exact: true })).toBeVisible()
    // Expire the server session outside React, then refetch the actual project list.
    await write(memberPage.request, '/api/auth/logout', {})
    await memberPage.getByLabel('Status projektów').selectOption('all')
    await expect(memberPage).toHaveURL(/\/login\?returnTo=/)
    expect(new URL(memberPage.url()).searchParams.get('returnTo')).toBe(`/projects?team=${team.id}`)
    await memberPage.getByLabel('Adres e-mail', { exact: true }).fill(memberEmail!)
    await memberPage.getByLabel('Hasło', { exact: true }).fill(memberPassword!)
    await memberPage.getByRole('button', { name: 'Zaloguj się', exact: true }).click()
    await expect(memberPage).toHaveURL(new RegExp(`/projects\\?team=${team.id}`))
    await expect(memberPage.getByRole('button', { name: project.name, exact: true })).toBeVisible()
  } finally { await context.close() }
})
