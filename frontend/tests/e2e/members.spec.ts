import { test, expect, setupTeam, create, login, member } from '../support/e2e'

test('owner removes a member while preserving history and allowing the member to finish their timer', async ({ page, browser }, info) => {
  const { team, project } = await setupTeam(page, `Members ${info.project.name} ${Date.now()}`)
  const invite = await create(page.request, `/api/teams/${team.id}/invites`, { expiresAt: new Date(Date.now() + 3600000).toISOString(), maxUses: 3 })
  const memberContext = await browser.newContext({ baseURL: new URL(page.url()).origin })
  try {
    const memberPage = await memberContext.newPage()
    await login(memberPage, member)
    await create(memberPage.request, `/api/invites/${invite.token}/accept`, {})
    const actor = await (await memberPage.request.get('/api/me')).json()
    const dates = await (await memberPage.request.get(`/api/dashboard/summary?teamId=${team.id}`)).json()
    await create(memberPage.request, '/api/time-entries', { teamId: team.id, projectId: project.id,
      workDate: dates.today, durationSeconds: 900, description: 'Preserved member work' })
    await create(memberPage.request, '/api/timer/start', { teamId: team.id, projectId: project.id, description: 'Active work' })
    await memberPage.goto(`/time?team=${team.id}`)
    await expect(memberPage.getByRole('button', { name: 'Wstrzymaj timer' })).toBeEnabled()
    await memberPage.getByRole('button', { name: 'Wstrzymaj timer' }).click()
    await expect(memberPage.getByRole('button', { name: 'Wznów pracę' })).toBeVisible()

    await page.goto(`/teams?team=${team.id}`)
    const remove = page.getByRole('button', { name: 'Usuń z zespołu: User Two', exact: true })
    await remove.click()
    let modal = page.getByRole('dialog', { name: 'Usuń członka zespołu' })
    await expect(modal).toContainText('User Two')
    await modal.getByRole('button', { name: 'Anuluj' }).click()
    expect((await (await memberPage.request.get('/api/teams')).json()).some((item: { id: string }) => item.id === team.id)).toBe(true)
    await remove.click()
    modal = page.getByRole('dialog', { name: 'Usuń członka zespołu' })
    await modal.getByRole('button', { name: 'Potwierdź usunięcie' }).click()
    await expect(modal).not.toBeVisible()
    await expect(page.getByRole('region', { name: 'Lista członków zespołu' })).not.toContainText('User Two')
    await page.getByLabel('Pokaż również byłych członków').check()
    const list = page.getByRole('region', { name: 'Lista członków zespołu' })
    await expect(list).toContainText('User Two')
    await expect(list).toContainText('Były członek')
    await page.screenshot({ path: info.outputPath('team-members.png'), fullPage: true, animations: 'disabled' })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect((await memberPage.request.get(`/api/teams/${team.id}/members`)).status()).toBe(404)
    expect((await memberPage.request.get(`/api/teams/${team.id}/projects`)).status()).toBe(404)

    await memberPage.reload()
    await expect(memberPage.getByRole('button', { name: 'Wznów pracę' })).toBeDisabled()
    await memberPage.getByRole('button', { name: 'Zakończ pracę' }).click()
    await expect(memberPage.getByRole('region', { name: 'Aktywny timer', exact: true })).toHaveCount(0)
    const summary = await (await page.request.get(`/api/teams/${team.id}/reports/summary`)).json()
    expect(summary.totals.durationSeconds).toBeGreaterThanOrEqual(901)
    expect(summary.totals.entryCount).toBe(2)

    await create(memberPage.request, `/api/invites/${invite.token}/accept`, {})
    await memberPage.goto(`/teams?team=${team.id}`)
    await expect(memberPage.getByRole('region', { name: 'Lista członków zespołu' })).toContainText('User One')
    await expect(memberPage.getByLabel('Pokaż również byłych członków')).toHaveCount(0)
    await expect(memberPage.getByRole('button', { name: /Usuń z zespołu:/ })).toHaveCount(0)
    await memberPage.getByRole('button', { name: 'Opuść zespół', exact: true }).click()
    const leave = memberPage.getByRole('dialog', { name: 'Opuść zespół' })
    await expect(leave).toContainText(team.name)
    await leave.getByRole('button', { name: 'Potwierdź opuszczenie' }).click()
    await expect(leave).not.toBeVisible()
    await expect(memberPage.getByText('Nie należysz jeszcze do żadnego zespołu.')).toBeVisible()
    await expect(memberPage.getByText(`Opuszczono zespół ${team.name}. Historia Twojej pracy została zachowana.`)).toBeVisible()
    const historical = await (await page.request.get(`/api/teams/${team.id}/members?includeFormer=true`)).json()
    expect(historical.content.find((item: { userId: string }) => item.userId === actor.id).leftAt).toBeTruthy()
  } finally {
    await memberContext.close()
  }
})
