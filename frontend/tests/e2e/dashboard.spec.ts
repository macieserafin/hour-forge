import { test, expect, setupTeam, create } from '../support/e2e'

test('personal dashboard sums saved time, follows corrections and keeps a timer visible across teams', async ({ page }, info) => {
  const { team, project } = await setupTeam(page, `Dashboard ${info.project.name} ${Date.now()}`)
  const second = await create(page.request, '/api/teams', { name: 'Other dashboard team', timezone: 'UTC' })
  await page.goto(`/dashboard?team=${team.id}`)
  const today = page.getByRole('region', { name: 'Czas dzisiaj' })
  const week = page.getByRole('region', { name: 'Czas w tym tygodniu' })
  await expect(today).toContainText('00:00:00')
  const dates = await (await page.request.get(`/api/dashboard/summary?teamId=${team.id}`)).json()
  await page.getByRole('link', { name: 'Przejdź do historii i rejestru czasu' }).click()
  await page.getByLabel('Projekt', { exact: true }).selectOption(project.id)
  await page.getByRole('button', { name: 'Dodaj wpis ręczny' }).click()
  let modal = page.getByRole('dialog')
  await modal.getByLabel('Data pracy').fill(dates.today)
  await modal.getByLabel('Minuty').fill('15')
  await modal.getByRole('button', { name: 'Zapisz wpis' }).click()
  await expect(modal).not.toBeVisible()
  await page.goto(`/dashboard?team=${team.id}`)
  await expect(today).toContainText('00:15:00')
  await expect(week).toContainText('00:15:00')
  await page.getByRole('link', { name: 'Przejdź do historii i rejestru czasu' }).click()
  await page.getByRole('button', { name: 'Edytuj', exact: true }).click()
  modal = page.getByRole('dialog')
  await modal.getByLabel('Minuty').fill('30')
  await modal.getByRole('button', { name: 'Zapisz zmiany' }).click()
  await expect(modal).not.toBeVisible()
  await page.goto(`/dashboard?team=${team.id}`)
  await expect(today).toContainText('00:30:00')
  await page.getByRole('link', { name: 'Przejdź do historii i rejestru czasu' }).click()
  await page.getByLabel('Projekt', { exact: true }).selectOption(project.id)
  await page.getByRole('button', { name: 'Uruchom timer', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Aktywny timer', exact: true }).getByRole('button', { name: 'Wstrzymaj timer' })).toBeEnabled()
  await page.getByRole('button', { name: 'Wstrzymaj timer' }).click()
  await expect(page.getByRole('region', { name: 'Aktywny timer', exact: true })).toContainText('Praca wstrzymana')
  await page.goto(`/dashboard?team=${team.id}`)
  const active = page.getByRole('region', { name: 'Aktywny timer na pulpicie' })
  await expect(active).toContainText('Timer wstrzymany')
  await expect(today).toContainText('00:30:00')
  await page.screenshot({ path: info.outputPath('personal-dashboard.png'), fullPage: true, animations: 'disabled' })
  await page.getByLabel('Zespół na pulpicie').selectOption(second.id)
  await expect(today).toContainText('00:00:00')
  await expect(active).toContainText(project.name)
  await active.getByRole('link', { name: 'Przejdź do timera' }).click()
  await page.getByRole('button', { name: 'Zakończ pracę' }).click()
  await expect(page.getByRole('region', { name: 'Aktywny timer', exact: true })).toHaveCount(0)
  await page.goto(`/dashboard?team=${team.id}`)
  await expect(active).toHaveCount(0)
  const saved = await (await page.request.get(`/api/dashboard/summary?teamId=${team.id}`)).json()
  expect(saved.todaySeconds).toBeGreaterThan(1800)
  await page.getByRole('link', { name: 'Przejdź do historii i rejestru czasu' }).click()
  for (let count = 2; count > 0; count--) {
    await page.getByRole('button', { name: 'Usuń', exact: true }).first().click()
    await page.getByRole('dialog').getByRole('button', { name: 'Usuń wpis', exact: true }).click()
    await expect(page.getByRole('dialog')).not.toBeVisible()
  }
  await page.goto(`/dashboard?team=${team.id}`)
  await expect(today).toContainText('00:00:00')
  await expect(week).toContainText('00:00:00')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
