import { test, expect, member as memberEmail, memberPassword, login, post, create, createTeamProject as setup } from '../support/e2e'

test('timer survives refresh and team changes while manual entries can be saved', { tag: '@responsive' }, async ({ page }, testInfo) => {
  await login(page)
  const suffix = `${testInfo.project.name} ${Date.now()}`
  const first = await setup(page, suffix)
  const second = await setup(page, `Other ${suffix}`)
  const archived = await create(page.request, `/api/teams/${second.team.id}/projects`, { name: 'Archived project', description: null })
  await create(page.request, `/api/teams/${second.team.id}/projects/${archived.id}/archive`, {})
  await page.goto(`/projects?team=${first.team.id}`)
  await expect(page.getByRole('heading', { name: 'Projekty', exact: true })).toBeVisible()
  const menu = page.getByRole('button', { name: 'Otwórz menu' })
  if (await menu.isVisible()) await menu.click()
  await page.getByRole('link', { name: 'Rejestr czasu', exact: true }).filter({ visible: true }).click()
  await expect(page.getByLabel('Zespół', { exact: true })).toHaveValue(first.team.id)
  const input = page.getByRole('region', { name: 'Rejestrowanie czasu w zespole' })
  await input.getByLabel('Projekt', { exact: true }).selectOption(first.project.id)
  await input.getByLabel('Opis pracy', { exact: false }).fill('Projektowanie widoku')
  const startResponse = page.waitForResponse(response => response.url().endsWith('/api/timer/start') && response.request().method() === 'POST')
  await input.getByRole('button', { name: 'Uruchom timer', exact: true }).click()
  const started = await (await startResponse).json()
  const active = page.getByRole('region', { name: 'Aktywny timer', exact: true })
  await expect(active).toContainText(first.project.name)
  await expect(active.getByRole('timer')).not.toHaveText('00:00:00')
  await expect(input.getByRole('button', { name: 'Uruchom timer' })).toBeDisabled()
  await page.reload()
  await expect(active).toContainText(first.project.name)
  expect((await (await page.request.get('/api/timer/active')).json()).id).toBe(started.id)
  await page.getByLabel('Zespół', { exact: true }).selectOption(second.team.id)
  await expect(active).toContainText(first.team.name)
  await expect(input.getByLabel('Projekt', { exact: true }).getByRole('option', { name: 'Archived project', exact: true })).toHaveCount(0)
  await input.getByLabel('Projekt', { exact: true }).selectOption(second.project.id)
  await input.getByRole('button', { name: 'Dodaj wpis ręczny' }).click()
  const manual = page.getByRole('dialog', { name: 'Dodaj wpis ręczny' })
  await expect(manual).toContainText(second.team.name)
  await expect(manual.getByLabel('Projekt', { exact: true })).toHaveValue(second.project.id)
  await manual.getByLabel('Data pracy').fill('2026-01-05')
  await manual.getByRole('button', { name: 'Zapisz wpis' }).click()
  await expect(manual.getByRole('alert')).toContainText('Podaj dodatni czas')
  await manual.getByLabel('Godziny').fill('1')
  await manual.getByLabel('Minuty').fill('2')
  await manual.getByLabel('Sekundy').fill('3')
  await expect(manual.getByRole('alert')).toHaveCount(0)
  await manual.getByLabel('Opis pracy', { exact: false }).fill('Ręcznie zarejestrowana praca')
  await page.screenshot({ path: testInfo.outputPath('manual-time-modal.png'), fullPage: false, animations: 'disabled' })
  const manualResponse = page.waitForResponse(response => response.url().endsWith('/api/time-entries') && response.request().method() === 'POST')
  await manual.getByRole('button', { name: 'Zapisz wpis' }).click()
  const entry = await (await manualResponse).json()
  expect(entry).toMatchObject({ teamId: second.team.id, projectId: second.project.id, entryType: 'MANUAL', workDate: '2026-01-05', durationSeconds: 3723, startedAt: null, endedAt: null })
  await expect(manual).not.toBeVisible()
  await expect(page.getByRole('status').filter({ hasText: 'Wpis ręczny zapisany' })).toContainText('01:02:03')
  expect((await (await page.request.get('/api/timer/active')).json()).id).toBe(started.id)
  await page.reload()
  await expect(page.getByLabel('Zespół', { exact: true })).toHaveValue(second.team.id)
  await expect(active).toContainText(first.project.name)
  await active.getByLabel('Opis wykonanej pracy', { exact: false }).fill('Gotowy widok rejestru czasu')
  await page.screenshot({ path: testInfo.outputPath('running-timer.png'), fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const stopResponse = page.waitForResponse(response => response.url().endsWith('/api/timer/stop') && response.request().method() === 'POST')
  await active.getByRole('button', { name: 'Zakończ pracę' }).click()
  const stopped = await (await stopResponse).json()
  expect(stopped.id).toBe(started.id)
  expect(stopped.durationSeconds).toBeGreaterThan(0)
  expect(stopped.description).toBe('Gotowy widok rejestru czasu')
  await expect(active).toHaveCount(0)
  await expect(page.getByText('Żaden timer nie jest uruchomiony.')).toBeVisible()
  expect((await page.request.get('/api/timer/active')).status()).toBe(204)
  await expect(input.getByRole('button', { name: 'Uruchom timer' })).toBeEnabled()
})

test('a timer started outside the page is recovered on conflict and archived project is rejected', async ({ page }, testInfo) => {
  await login(page)
  const { team, project } = await setup(page, `Conflict ${testInfo.project.name} ${Date.now()}`)
  await page.goto(`/time?team=${team.id}`)
  await page.getByLabel('Projekt', { exact: true }).selectOption(project.id)
  const start = page.getByRole('button', { name: 'Uruchom timer', exact: true })
  await expect(start).toBeEnabled()
  const external = await create(page.request, '/api/timer/start', { teamId: team.id, projectId: project.id })
  await start.click()
  await expect(page.getByRole('alert')).toContainText('Nie można uruchomić timera.')
  const active = page.getByRole('region', { name: 'Aktywny timer', exact: true })
  await expect(active).toContainText(project.name)
  expect((await (await page.request.get('/api/timer/active')).json()).id).toBe(external.id)
  await expect(active.getByRole('button', { name: 'Zakończ pracę' })).toBeEnabled()
  await active.getByRole('button', { name: 'Zakończ pracę' }).click()
  await expect(active).toHaveCount(0)
  await expect(start).toBeEnabled()
  await page.getByRole('button', { name: 'Dodaj wpis ręczny' }).click()
  const manual = page.getByRole('dialog', { name: 'Dodaj wpis ręczny' })
  await manual.getByLabel('Minuty').fill('15')
  await create(page.request, `/api/teams/${team.id}/projects/${project.id}/archive`, {})
  await manual.getByRole('button', { name: 'Zapisz wpis' }).click()
  await expect(manual.getByRole('alert')).toHaveText('Projekt jest zarchiwizowany i nie można dodać do niego czasu.')
  await manual.getByRole('button', { name: 'Anuluj' }).click()
  await expect(page.getByText('Brak aktywnych projektów.', { exact: true })).toBeVisible()
})

test('members can record time and resume after session expiration', async ({ page }, testInfo) => {
  await login(page)
  const { team, project } = await setup(page, `Member ${testInfo.project.name} ${Date.now()}`)
  const invite = await create(page.request, `/api/teams/${team.id}/invites`, { expiresAt: new Date(Date.now() + 3600000).toISOString(), maxUses: 1 })
  expect((await post(page.request, '/api/auth/logout', {})).ok()).toBe(true)
  await login(page, memberEmail!, memberPassword!)
  await create(page.request, `/api/invites/${invite.token}/accept`, {})
  await page.goto(`/time?team=${team.id}`)
  await page.getByLabel('Projekt', { exact: true }).selectOption(project.id)
  await page.getByRole('button', { name: 'Uruchom timer', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Aktywny timer', exact: true })).toContainText(project.name)
  expect((await post(page.request, '/api/auth/logout', {})).ok()).toBe(true)
  await page.reload()
  await expect(page).toHaveURL(/\/login\?returnTo=/)
  expect(new URL(page.url()).searchParams.get('returnTo')).toBe(`/time?team=${team.id}`)
  await page.getByLabel('Adres e-mail', { exact: true }).fill(memberEmail!)
  await page.getByLabel('Hasło', { exact: true }).fill(memberPassword!)
  await page.getByRole('button', { name: 'Zaloguj się', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`/time\\?team=${team.id}`))
  const active = page.getByRole('region', { name: 'Aktywny timer', exact: true })
  await expect(active).toContainText(project.name)
  await expect(active.getByRole('button', { name: 'Zakończ pracę' })).toBeEnabled()
  await active.getByRole('button', { name: 'Zakończ pracę' }).click()
  await expect(active).toHaveCount(0)
  await page.goto('/time?team=00000000-0000-0000-0000-000000000000')
  await expect(page.getByRole('alert')).toContainText('Ten zespół nie istnieje lub nie masz do niego dostępu.')
  await expect(page.getByRole('button', { name: 'Uruchom timer' })).toHaveCount(0)
})

test('pause survives refresh, resume continues counting and finish excludes breaks', async ({ page }, testInfo) => {
  await login(page)
  const { team, project } = await setup(page, `Pause ${testInfo.project.name} ${Date.now()}`)
  await page.goto(`/time?team=${team.id}`)
  await page.getByLabel('Projekt', { exact: true }).selectOption(project.id)
  await page.getByRole('button', { name: 'Uruchom timer', exact: true }).click()
  const active = page.getByRole('region', { name: 'Aktywny timer', exact: true })
  await expect(active.getByRole('button', { name: 'Wstrzymaj timer' })).toBeEnabled()
  await active.getByLabel('Opis wykonanej pracy', { exact: false }).fill('Opis zachowany podczas przerwy')
  const pauseResponse = page.waitForResponse(response => response.url().endsWith('/api/timer/pause') && response.request().method() === 'POST')
  await active.getByRole('button', { name: 'Wstrzymaj timer' }).click()
  const paused = await (await pauseResponse).json()
  expect(paused.pausedAt).toBeTruthy()
  expect(paused.endedAt).toBeNull()
  await expect(active).toContainText('Praca wstrzymana')
  const frozen = await active.getByRole('timer').textContent()
  const afterBreak = Date.now() + 1300
  await expect.poll(() => Date.now()).toBeGreaterThan(afterBreak)
  await expect(active.getByRole('timer')).toHaveText(frozen!)
  await expect(page.getByRole('button', { name: 'Uruchom timer' })).toBeDisabled()
  await page.reload()
  await expect(active).toContainText('Praca wstrzymana')
  await expect(active.getByRole('timer')).toHaveText(frozen!)
  await expect(active.getByLabel('Opis wykonanej pracy', { exact: false })).toHaveValue('Opis zachowany podczas przerwy')
  await page.screenshot({ path: testInfo.outputPath('paused-timer.png'), fullPage: true, animations: 'disabled' })
  const resumeResponse = page.waitForResponse(response => response.url().endsWith('/api/timer/resume') && response.request().method() === 'POST')
  await active.getByRole('button', { name: 'Wznów pracę' }).click()
  const resumed = await (await resumeResponse).json()
  expect(resumed.id).toBe(paused.id)
  expect(resumed.pausedAt).toBeNull()
  expect(resumed.pausedDurationSeconds).toBeGreaterThan(1)
  await expect(active).toContainText('Timer działa')
  await expect(active.getByRole('timer')).not.toHaveText(frozen!)
  await active.getByRole('button', { name: 'Wstrzymaj timer' }).click()
  await expect(active).toContainText('Praca wstrzymana')
  const finishedCounter = await active.getByRole('timer').textContent()
  const expectedSeconds = finishedCounter!.split(':').reduce((total, part) => total * 60 + Number(part), 0)
  const finalResponse = page.waitForResponse(response => response.url().endsWith('/api/timer/stop') && response.request().method() === 'POST')
  await active.getByRole('button', { name: 'Zakończ pracę' }).click()
  const finished = await (await finalResponse).json()
  expect(finished.id).toBe(paused.id)
  expect(finished.durationSeconds).toBe(expectedSeconds)
  expect(finished.pausedAt).toBeNull()
  expect(finished.endedAt).toBeTruthy()
  await expect(active).toHaveCount(0)
  await expect(page.getByRole('status').filter({ hasText: 'Praca zakończona i zapisana' })).toBeVisible()
  expect((await page.request.get('/api/timer/active')).status()).toBe(204)
})
